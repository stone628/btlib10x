/**
 * Heat accumulation and the Total Warfare Heat Scale (BattleTech Total Warfare
 * subset). Pure functions over a unit's heat value and crit-slot state.
 *
 * Heat is recorded *during* the turn as it is generated (movement heat at the
 * moment a move is committed, weapon heat after each attack resolution), so
 * to-hit modifiers in the weapon attack phase already include that turn's
 * movement heat. Dissipation, shutdown/restart checks and heat ammo
 * explosions are processed once per turn when the end phase runs
 * (`resolveHeatPhase` in game.ts).
 *
 * Heat sinks come from the `heatsink` config (MTF `Heat Sinks:N Type` header)
 * plus the crit-slot table. Per construction rules an engine mounts
 * `floor(walking * tonnage / 25)` sinks internally at no crit cost; every
 * remaining sink (up to the configured total) occupies crit slots — single
 * sinks one slot each, double sinks grouped in runs of 3 (Inner Sphere) or
 * 2 (Clan) slots per device. Single sinks dissipate 1 heat per turn, double
 * sinks 2 per turn. Engine critical hits generate extra heat but do not
 * destroy heat sinks (strict Total Warfare).
 */

import { LOCATIONS, type Location, type MoveMode } from "../core/types.js";
import type { ResolvedMechDef } from "../data/mech.schema.js";
import { type AmmoBin, type AmmoBinId, collectAmmoBins } from "./ammo.js";
import { ammoDamagePerShot, type EffectiveMovement } from "./critical.js";
import { maxMovePoints } from "./movement.js";

export const HEAT_CAP = 50;

/** Engine-mounted sink capacity: floor(rating / 25), rating = walking * tonnage. */
export function engineInternalSinks(def: ResolvedMechDef): number {
  return Math.floor((def.walking * def.tonnage) / 25);
}

/** Crit slots occupied by one double heat sink device, by tech base. */
export function dhsCritWidth(def: ResolvedMechDef): number {
  return def.techBase === "Clan" ? 2 : 3;
}

/** Heat generated by committing a move. Jump = max(3, hexes jumped). */
export function movementHeat(mode: MoveMode, mpSpent: number): number {
  switch (mode) {
    case "standStill":
      return 0;
    case "walk":
      return mpSpent > 0 ? 1 : 0;
    case "run":
      return mpSpent > 0 ? 2 : 0;
    case "jump":
      return mpSpent > 0 ? Math.max(3, mpSpent) : 0;
  }
}

/**
 * Heat added per turn per destroyed engine slot: +5 for the first hit, +10
 * (acting as +5 for each additional hit) once two or more engine slots are
 * gone.
 */
export function engineHitHeat(destroyedEngineSlots: number): number {
  if (destroyedEngineSlots <= 0) return 0;
  return destroyedEngineSlots >= 2 ? 10 : 5;
}

/** Number of destroyed `engine` crit slots on the 'Mech. */
export function countDestroyedEngineSlots(
  def: ResolvedMechDef,
  critSlotsDestroyed: Readonly<Record<Location, readonly boolean[]>>,
): number {
  let n = 0;
  for (const loc of LOCATIONS) {
    const layout = def.critSlots[loc];
    const destroyed = critSlotsDestroyed[loc];
    for (let i = 0; i < layout.length; i++) {
      const slot = layout[i];
      if (slot?.kind === "structure" && slot.name === "engine" && (destroyed?.[i] ?? false)) {
        n += 1;
      }
    }
  }
  return n;
}

/**
 * Operational heat sinks: engine-internal sinks (`floor(rating/25)`, never
 * destroyed by engine crits) plus one per intact external sink device — each
 * non-destroyed `heatSink` slot, and each intact double-heat-sink group (a
 * 3-slot IS run or 2-slot Clan run = one device). Capped at the configured
 * total (`heatsink.count`), so an engine with spare capacity never reports
 * sinks the 'Mech does not carry.
 */
export function heatSinksOperational(
  def: ResolvedMechDef,
  critSlotsDestroyed: Readonly<Record<Location, readonly boolean[]>>,
): number {
  const internal = engineInternalSinks(def);
  const width = dhsCritWidth(def);
  let external = 0;
  for (const loc of LOCATIONS) {
    const layout = def.critSlots[loc];
    const destroyed = critSlotsDestroyed[loc];
    for (let i = 0; i < layout.length; i++) {
      const slot = layout[i];
      if (slot?.kind !== "structure") continue;
      if (slot.name === "heatSink") {
        if (!(destroyed?.[i] ?? false)) external += 1;
      } else if (slot.name === "doubleHeatSink") {
        // Count a DHS device once (via its first slot); the whole group is
        // destroyed together by a single critical hit.
        const group = slot.group;
        if (group[0] !== i + 1) continue;
        const anyDestroyed = group.some((j) => destroyed?.[j - 1] ?? false);
        if (!anyDestroyed) external += Math.floor(group.length / width);
      }
    }
  }
  return Math.min(def.heatsink.count, internal + external);
}

/**
 * Heat removed per turn in the end phase: each operational single sink removes
 * 1 heat, each operational double sink removes 2.
 */
export function heatDissipation(
  def: ResolvedMechDef,
  critSlotsDestroyed: Readonly<Record<Location, readonly boolean[]>>,
): number {
  const sinks = heatSinksOperational(def, critSlotsDestroyed);
  return def.heatsink.type === "double" ? sinks * 2 : sinks;
}

// Total Warfare Heat Scale breakpoints (ascending).

/** To-hit modifier from the Heat Scale table (8 / 13 / 17 / 24+). */
export function toHitHeatModifier(heat: number): number {
  return toHitHeatModifierWithThreshold(heat).toHit;
}

export function toHitHeatModifierWithThreshold(heat: number): { toHit: number; threshold: number } {
  if (heat >= 24) return { toHit: 4, threshold: 24 };
  if (heat >= 17) return { toHit: 3, threshold: 17 };
  if (heat >= 13) return { toHit: 2, threshold: 13 };
  if (heat >= 8) return { toHit: 1, threshold: 8 };
  return { toHit: 0, threshold: 0 };
}

/** Movement point penalty from the Heat Scale table (5 / 10 / 15 / 20 / 25+). */
export function movementMpPenalty(heat: number): number {
  return movementMpPenaltyWithThreshold(heat).penalty;
}

export function movementMpPenaltyWithThreshold(heat: number): {
  penalty: number;
  threshold: number;
} {
  if (heat >= 25) return { penalty: 5, threshold: 25 };
  if (heat >= 20) return { penalty: 4, threshold: 20 };
  if (heat >= 15) return { penalty: 3, threshold: 15 };
  if (heat >= 10) return { penalty: 2, threshold: 10 };
  if (heat >= 5) return { penalty: 1, threshold: 5 };
  return { penalty: 0, threshold: 0 };
}

/** Movement budget after the heat MP penalty, floor 0. */
export function effectiveMoveBudget(
  mode: MoveMode,
  movement: EffectiveMovement,
  heat: number,
): number {
  const base = maxMovePoints(mode, movement.walking, movement.running, movement.jumping);
  return Math.max(0, base - movementMpPenalty(heat));
}

/** Shutdown avoidance number at the current heat, or null when no shutdown risk. */
export function shutdownAvoid(heat: number): number {
  return shutdownAvoidWithThreshold(heat).avoid;
}

export function shutdownAvoidWithThreshold(heat: number): { avoid: number; threshold: number } {
  if (heat >= 30) return { avoid: 12, threshold: 30 };
  if (heat >= 26) return { avoid: 10, threshold: 26 };
  if (heat >= 22) return { avoid: 8, threshold: 22 };
  if (heat >= 18) return { avoid: 6, threshold: 18 };
  if (heat >= 14) return { avoid: 4, threshold: 14 };
  return { avoid: 0, threshold: 0 };
}

/** Heat ammo-explosion avoidance number at the current heat, or null when none. */
export function ammoExplosionAvoid(heat: number): number {
  return ammoExplosionAvoidWithThreshold(heat).avoid;
}

export const AMMO_EXPLOSION_START_HEAT = 19;

export function ammoExplosionAvoidWithThreshold(heat: number): {
  avoid: number;
  threshold: number;
} {
  if (heat >= 28) return { avoid: 8, threshold: 28 };
  if (heat >= 23) return { avoid: 6, threshold: 23 };
  if (heat >= AMMO_EXPLOSION_START_HEAT) return { avoid: 4, threshold: AMMO_EXPLOSION_START_HEAT };
  return { avoid: 0, threshold: 0 };
}

export interface HeatScaleEffects {
  readonly heat: number;
  readonly toHitMod: number;
  readonly mpPenalty: number;
  /** Null = no shutdown risk; "auto" = heat 30+; otherwise avoid on `avoid`. */
  readonly shutdown: null | { readonly threshold: number; readonly avoid: number } | "auto";
  /** Null = no ammo-explosion risk; otherwise avoid on `avoid`. */
  readonly ammoExplosion: null | { readonly threshold: number; readonly avoid: number };
}

/** All Heat Scale effects at a given heat value, for display. */
export function heatScaleEffects(heat: number): HeatScaleEffects {
  let shutdown: HeatScaleEffects["shutdown"] = null;
  {
    const { avoid, threshold } = shutdownAvoidWithThreshold(heat);
    if (avoid >= 12) {
      // max 2D6 == 12, always
      shutdown = "auto";
    } else {
      shutdown = { threshold, avoid };
    }
  }
  let ammoExplosion: HeatScaleEffects["ammoExplosion"] = null;
  {
    const { avoid, threshold } = ammoExplosionAvoidWithThreshold(heat);

    if (avoid > 0) {
      // avoid exists
      ammoExplosion = { threshold, avoid };
    }
  }
  return {
    heat,
    toHitMod: toHitHeatModifier(heat),
    mpPenalty: movementMpPenalty(heat),
    shutdown,
    ammoExplosion,
  };
}

export interface LargestAmmoBin {
  readonly binId: AmmoBinId;
  /** Every bin backing the detonating weapon mount, in slot order. */
  readonly binIds: readonly AmmoBinId[];
  readonly weapon: string;
  readonly location: Location;
  readonly slotIndex: number;
  readonly shotsRemaining: number;
  readonly damagePerShot: number;
  readonly damage: number;
}

/**
 * The ammo bin that would detonate in a heat-triggered ammo explosion: the
 * weapon mount whose remaining shots x per-shot damage is largest. The mount
 * aggregates every loaded bin it owns (so the full magazine detonates
 * together); ties resolve to the first-found mount, deterministic. Returns
 * null when the 'Mech carries no loaded ammunition.
 */
export function largestAmmoBin(
  def: ResolvedMechDef,
  ammoBins: Readonly<Record<AmmoBinId, number>>,
): LargestAmmoBin | null {
  const byMount = new Map<number, AmmoBin[]>();
  for (const bin of collectAmmoBins(def)) {
    const list = byMount.get(bin.weaponIndex) ?? [];
    list.push(bin);
    byMount.set(bin.weaponIndex, list);
  }
  let best: LargestAmmoBin | null = null;
  for (const bins of byMount.values()) {
    const shotsRemaining = bins.reduce((s, b) => s + (ammoBins[b.id] ?? 0), 0);
    if (shotsRemaining <= 0) continue;
    const first = bins[0]!;
    const damagePerShot = ammoDamagePerShot(first);
    const candidate: LargestAmmoBin = {
      binId: first.id,
      binIds: bins.map((b) => b.id),
      weapon: first.weapon,
      location: first.location,
      slotIndex: first.slotIndex,
      shotsRemaining,
      damagePerShot,
      damage: shotsRemaining * damagePerShot,
    };
    if (best === null || candidate.damage > best.damage) best = candidate;
  }
  return best;
}
