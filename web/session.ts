export interface Session {
  app: AppState;
  /** Output language (UI preference; preserved across reset/rematch). */
  locale: LocaleId;
  rng: Rng;
  setup: SetupState;
  battle: BattleState | null;
  victory: VictoryResult | null;
  actorId: string | null;
  /** Pending declaration for the acting unit: a movement mode (engine
   *  `MoveMode`), a posture-change `standup` / `prone` attempt, or
   *  the voluntary `"shutdown"` / `"startup"` / `"eject"` declaration,
   *  committed by the `done` command. `standup` / `prone` may carry a queued
   *  `place` landing in `placedLanding`; `postureMove` holds the locomotion
   *  mode the queued steps run under after the posture change succeeds. */
  moveMode:
    | MoveMode
    | "shutdown"
    | "startup"
    | "eject"
    | "standup"
    | "prone"
    | "turn"
    | "pronestill"
    | null;
  /** Locomotion mode for a posture-change + move: `walk` for `prone turn`
   *  (in-place turns after the drop), `standStill` for `prone pronestill`,
   *  the declared walk/run/jump for `standup`. Null otherwise. */
  postureMove: MoveMode | null;
  moveSteps: MoveStep[];
  /** Landing facing chosen by `place` (jump only: engine rejects turn steps
   *  while jumping, so the landing facing travels via `executeMove`'s
   *  `finalFacing` option). Null when unset or ground movement. */
  moveFinalFacing: Facing | null;
  /** Landing from `moveCandidate` buffered by `place`; `status`/`candidate`
   *  preview renders its `path` directly. Null when no landing queued. */
  placedLanding: RevealedLanding | null;
  fireDecls: AttackDecl[];
  /** Acting unit's torso twist (TW p.62) for the current attack-phase
   *  declaration: defaults to `"front"` and resets every time a new actor
   *  becomes current or the weapon attack phase begins. Locked once any
   *  fire command is queued (see {@link setTorsoTwist}). Session-owned
   *  because it is a UI declaration, not persistent battle state. */
  torsoTwist: Arc;
  /** Suppress critical hit resolution (mostly for deterministic testing). */
  critsDisabled: boolean;
  moveCandidate: BoardRenderReachableInfo | null;
  /** Actor (turn-qualified) whose fire suggestion was last auto-shown. */
  fireHintShownFor: string | null;
  fireCandidate: FireSuggestion | null;
}

export function newSession(seed: number): Session {
  return {
    app: "setup",
    locale: "en",
    rng: createRng(seed),
    setup: { mapName: null, seed: seed, roster: [] },
    battle: null,
    victory: null,
    actorId: null,
    moveMode: null,
    postureMove: null,
    moveSteps: [],
    moveFinalFacing: null,
    placedLanding: null,
    fireDecls: [],
    torsoTwist: "front",
    critsDisabled: false,
    moveCandidate: null,
    fireHintShownFor: null,
    fireCandidate: null,
  };
}

function clearBuffers(s: Session): void {
  s.moveMode = null;
  s.postureMove = null;
  clearMoveQueue(s);
  s.moveCandidate = null;
  s.fireDecls = [];
  s.torsoTwist = "front";
  s.fireHintShownFor = null;
  s.fireCandidate = null;
}

/**
 * Advance the battle through transient phases until an actor must act or the
 * game ends. Returns the GameEvents generated by the phase transitions
 * (initiative rolls, the end-of-phase attack sweep, turn/phase markers).
 */
function drive(s: Session): GameEvent[] {
  const battle = s.battle;
  if (!battle) return [];
  const before = battle.events.length;
  for (let i = 0; i < 200; i++) {
    const v = checkVictory(battle);
    if (v.winnerTeam !== null || v.draw) {
      s.battle = battle;
      s.app = "over";
      s.victory = v;
      s.actorId = null;
      clearBuffers(s);
      return battle.events.slice(before);
    }
    if (battle.phase === "initiative") {
      rollInitiativePhase(battle, s.rng);
      continue;
    }
    if (battle.phase === "end") {
      advancePhase(battle, s.rng);
      continue;
    }
    const id = nextActor(battle);
    if (id !== null) {
      s.battle = battle;
      s.app = "battle";
      if (s.actorId !== id) {
        s.actorId = id;
        clearBuffers(s);
      }
      return battle.events.slice(before);
    }
    if (battle.phase === "weaponAttack") {
      resolveAllAttacks(battle, s.rng);
    }
    const prevPhase = battle.phase;
    advancePhase(battle, s.rng);
    if (prevPhase === "movement" && battle.phase === "weaponAttack") {
      s.torsoTwist = "front";
    }
  }
  throw new Error(i18n(s.locale, "err.phaseDriver"));
}

export function currentActor(s: Session): UnitState | null {
  if (s.app !== "battle" || !s.battle || s.actorId === null) return null;
  return getUnit(s.battle, s.actorId);
}

/** Prompt body without the trailing ">". */
export function promptBody(s: Session): string {
  switch (s.app) {
    case "setup":
      return i18n(s.locale, "prompt.setup");
    case "over": {
      const winner = s.victory?.draw
        ? i18n(s.locale, "prompt.draw")
        : i18n(s.locale, "prompt.winnerTeam", { team: s.victory?.winnerTeam ?? "?" });
      return i18n(s.locale, "prompt.over", {
        winner,
        turn: s.battle?.turn ?? "?",
      });
    }
    case "battle": {
      const st = s.battle!;
      const phase =
        st.phase === "movement"
          ? i18n(s.locale, "prompt.subMove")
          : i18n(s.locale, "prompt.subAttack");
      const actor = currentActor(s);
      return i18n(s.locale, "prompt.turn", {
        turn: st.turn,
        phase,
        team: actor?.team ?? "?",
        id: actor?.id ?? "?",
      });
    }
  }
}

