export type AppState = "setup" | "battle" | "over";

export interface SetupState extends MapNameHolder {
  seed: number;
  mapName: string | null;
  roster: UnitInit[];
}

export interface Session {
  app: AppState;
  /** Output language (UI preference; preserved across reset/rematch). */
  locale: LocaleId;
  rng: Rng;
  setup: SetupState;
  battle: BattleState | null;
  victory: VictoryResult | null;
  actorId: string | null;
  /** Pending declaration for the acting unit: a movement mode (engine
   *  `MoveMode`), a prone-mode `standup` / `drop` / `proneTurn` attempt, or
   *  the voluntary `"shutdown"` / `"startup"` / `"eject"` declaration,
   *  committed by the `done` command. */
  moveMode: MoveMode | "shutdown" | "startup" | "eject" | "standup" | "drop" | "proneTurn" | null;
  moveSteps: MoveStep[];
  /** Landing facing chosen by `place` (jump only: engine rejects turn steps
   *  while jumping, so the landing facing travels via `executeMove`'s
   *  `finalFacing` option). Null when unset or ground movement. */
  moveFinalFacing: Facing | null;
  /** Landing from `moveCandidate` buffered by `place`; `status`/`candidate`
   *  preview renders its `path` directly. Null when no landing queued. */
  placedLanding: RevealedLanding | null;
  /** Prone turn facings queued by `turn` (no candidate landing exists for it). */
  placedTurn: 1 | -1 | null;
  fireDecls: AttackDecl[];
  /** Suppress critical hit resolution (mostly for deterministic testing). */
  critsDisabled: boolean;
  moveCandidate: BoardRenderReachableInfo | null;
  /** Actor (turn-qualified) whose fire suggestion was last auto-shown. */
  fireHintShownFor: string | null;
  fireCandidate: FireSuggestion | null;
}

export function newSession(seed: number): Session {
  return {
    app: "setup",
    locale: "en",
    rng: createRng(seed),
    setup: { mapName: null, seed: seed, roster: [] },
    battle: null,
    victory: null,
    actorId: null,
    moveMode: null,
    moveSteps: [],
    moveFinalFacing: null,
    placedLanding: null,
    placedTurn: null,
    fireDecls: [],
    critsDisabled: false,
    moveCandidate: null,
    fireHintShownFor: null,
    fireCandidate: null,
  };
}

function clearBuffers(s: Session): void {
  s.moveMode = null;
  clearMoveQueue(s);
  s.moveCandidate = null;
  s.fireDecls = [];
  s.fireHintShownFor = null;
  s.fireCandidate = null;
}

/**
 * Advance the battle through transient phases until an actor must act or the
 * game ends. Returns the GameEvents generated by the phase transitions
 * (initiative rolls, the end-of-phase attack sweep, turn/phase markers).
 */
function drive(s: Session): GameEvent[] {
  const battle = s.battle;
  if (!battle) return [];
  const before = battle.events.length;
  for (let i = 0; i < 200; i++) {
    const v = checkVictory(battle);
    if (v.winnerTeam !== null || v.draw) {
      s.battle = battle;
      s.app = "over";
      s.victory = v;
      s.actorId = null;
      clearBuffers(s);
      return battle.events.slice(before);
    }
    if (battle.phase === "initiative") {
      rollInitiativePhase(battle, s.rng);
      continue;
    }
    if (battle.phase === "end") {
      advancePhase(battle, s.rng);
      continue;
    }
    const id = nextActor(battle);
    if (id !== null) {
      s.battle = battle;
      s.app = "battle";
      if (s.actorId !== id) {
        s.actorId = id;
        clearBuffers(s);
      }
      return battle.events.slice(before);
    }
    if (battle.phase === "weaponAttack") {
      resolveAllAttacks(battle, s.rng);
    }
    advancePhase(battle, s.rng);
  }
  throw new Error(i18n(s.locale, "err.phaseDriver"));
}

export function currentActor(s: Session): UnitState | null {
  if (s.app !== "battle" || !s.battle || s.actorId === null) return null;
  return getUnit(s.battle, s.actorId);
}

/** Prompt body without the trailing ">". */
export function promptBody(s: Session): string {
  switch (s.app) {
    case "setup":
      return i18n(s.locale, "prompt.setup");
    case "over": {
      const winner = s.victory?.draw
        ? i18n(s.locale, "prompt.draw")
        : i18n(s.locale, "prompt.winnerTeam", { team: s.victory?.winnerTeam ?? "?" });
      return i18n(s.locale, "prompt.over", {
        winner,
        turn: s.battle?.turn ?? "?",
      });
    }
    case "battle": {
      const st = s.battle!;
      const phase =
        st.phase === "movement"
          ? i18n(s.locale, "prompt.subMove")
          : i18n(s.locale, "prompt.subAttack");
      const actor = currentActor(s);
      return i18n(s.locale, "prompt.turn", {
        turn: st.turn,
        phase,
        team: actor?.team ?? "?",
        id: actor?.id ?? "?",
      });
    }
  }
}

// ---------------------------------------------------------------- setup ----

export function setMap(s: Session, m: MapDef): void {
  if (s.setup.mapName !== null) {
    for (const u of s.setup.roster) {
      if (u.position.col > m.width) {
        throw new Error(
          i18n(s.locale, "err.unitOutOfBounds", {
            id: u.id,
            label: "col",
            value: u.position.col,
            max: m.width,
          }),
        );
      }
      if (u.position.row > m.height) {
        throw new Error(
          i18n(s.locale, "err.unitOutOfBounds", {
            id: u.id,
            label: "row",
            value: u.position.row,
            max: m.height,
          }),
        );
      }
    }
  }
  s.setup.mapName = m.name;
}

export function addUnit(
  s: Session,
  id: string,
  model: string,
  team: number,
  gunnery: number,
  position: HexCoord,
  facing: Facing,
  piloting: number = 5,
): string {
  const m = lookupMech(model);
  if (m === undefined) throw new Error(i18n(s.locale, "err.unknownModel", { model }));
  if (s.setup.roster.some((u) => u.id === id))
    throw new Error(i18n(s.locale, "err.duplicateId", { id }));
  if (!Number.isInteger(team) || team < 0) throw new Error(i18n(s.locale, "err.badTeam"));
  if (!Number.isInteger(gunnery) || gunnery < 0 || gunnery > 7) {
    throw new Error(i18n(s.locale, "err.badGunnery"));
  }
  if (!Number.isInteger(piloting) || piloting < 0 || piloting > 7) {
    throw new Error(i18n(s.locale, "err.badPiloting"));
  }
  if (s.setup.roster.some((u) => sameHex(u.position, position))) {
    throw new Error(i18n(s.locale, "err.hexOccupied", { col: position.col, row: position.row }));
  }
  if (s.setup.mapName != null) {
    const map = getMapDefFor(s.setup);
    if (map !== undefined) {
      if (position.col > map.width) {
        throw new Error(
          i18n(s.locale, "err.outOfBounds", { label: "col", value: position.col, max: map.width }),
        );
      }
      if (position.row > map.height) {
        throw new Error(
          i18n(s.locale, "err.outOfBounds", { label: "row", value: position.row, max: map.height }),
        );
      }
    }
  }
  s.setup.roster.push({ id, model: m.model, team, gunnery, piloting, position, facing });
  return m.model;
}

export function removeUnit(s: Session, id: string): void {
  if (!s.setup.roster.some((u) => u.id === id))
    throw new Error(i18n(s.locale, "err.noSuchUnit", { id }));
  s.setup.roster = s.setup.roster.filter((u) => u.id !== id);
}

/** Shared createBattle options: setup terrain plus the loaded map's size. */
function battleOptions(s: Session): CreateBattleOptions {
  return {
    critsDisabled: s.critsDisabled,
  };
}

export function startBattle(s: Session): GameEvent[] {
  if (s.app !== "setup") throw new Error(i18n(s.locale, "err.alreadyStarted"));
  if (s.setup.roster.length < 2) throw new Error(i18n(s.locale, "err.needTwoUnits"));
  const teams = new Set(s.setup.roster.map((u) => u.team));
  if (teams.size < 2) throw new Error(i18n(s.locale, "err.needTwoTeams"));
  const map = getMapDefFor(s.setup);
  s.battle = createBattle(map, s.setup.roster, battleOptions(s));
  s.victory = null;
  s.actorId = null;
  clearBuffers(s);
  return drive(s);
}

// ------------------------------------------------------------- movement ----

const MOVE_MODES: Readonly<Record<string, MoveMode>> = {
  standstill: "standStill",
  walk: "walk",
  run: "run",
  jump: "jump",
};

const VOLUNTARY_MODES: Readonly<Record<string, "shutdown" | "startup" | "eject">> = {
  shutdown: "shutdown",
  startup: "startup",
  eject: "eject",
};

const PRONE_MODES: Readonly<Record<string, "standup" | "drop">> = {
  standup: "standup",
  drop: "drop",
};

export type DeclaredMode =
  | MoveMode
  | "shutdown"
  | "startup"
  | "eject"
  | "standup"
  | "drop"
  | "proneTurn";

export function parseMoveMode(locale: LocaleId, word: string): DeclaredMode {
  const mode = MOVE_MODES[word.toLowerCase()];
  if (mode) return mode;
  const voluntary = VOLUNTARY_MODES[word.toLowerCase()];
  if (voluntary) return voluntary;
  const prone = PRONE_MODES[word.toLowerCase()];
  if (prone) return prone;
  throw new Error(i18n(locale, "err.badModeWord"));
}

function requireBattle(s: Session): BattleState {
  if (!s.battle) throw new Error(i18n(s.locale, "err.noBattle"));
  return s.battle;
}

function requireActor(s: Session, phase: "movement" | "weaponAttack"): UnitState {
  const unit = currentActor(s);
  if (!unit || !s.battle || s.battle.phase !== phase) {
    throw new Error(i18n(s.locale, "err.wrongPhase", { phase }));
  }
  return unit;
}

export function declareMode(s: Session, word: string): void {
  const unit = requireActor(s, "movement");
  const mode = parseMoveMode(s.locale, word);
  if (mode === "shutdown") {
    if (isShutdown(unit)) throw new Error(i18n(s.locale, "err.mustBeOnlineForShutdown"));
    s.moveMode = "shutdown";
    clearMoveQueue(s);
    return;
  }
  if (mode === "startup") {
    if (unit.shutdown === "not") throw new Error(i18n(s.locale, "err.mustBeDownForStartup"));
    if (unit.shutdown === "starting") throw new Error(i18n(s.locale, "err.alreadyStarting"));
    s.moveMode = "startup";
    clearMoveQueue(s);
    return;
  }
  if (mode === "eject") {
    if (unit.removed) throw new Error(i18n(s.locale, "err.alreadyEjected", { id: unit.id }));
    s.moveMode = "eject";
    clearMoveQueue(s);
    return;
  }
  if (mode === "standup") {
    if (!unit.prone) throw new Error(i18n(s.locale, "err.standupRequiresProne", { id: unit.id }));
    s.moveMode = "standup";
    clearMoveQueue(s);
    return;
  }
  if (mode === "drop") {
    if (unit.prone) throw new Error(i18n(s.locale, "err.dropRequiresStanding", { id: unit.id }));
    s.moveMode = "drop";
    clearMoveQueue(s);
    return;
  }
  if (mode !== "standStill" && mode !== "walk" && mode !== "run" && mode !== "jump") {
    throw new Error(i18n(s.locale, "err.badModeWord"));
  }
  declareMove(requireBattle(s), unit.id, mode);
  s.moveMode = mode;
  clearMoveQueue(s);
}

/** Clear queued movement: steps, buffered landing/turn, landing facing. */
function clearMoveQueue(s: Session): void {
  s.moveSteps = [];
  s.placedLanding = null;
  s.placedTurn = null;
  s.moveFinalFacing = null;
}

/** Movement budget for the declared mode (stand-in modes map to standstill). */
export function budgetFor(s: Session): number {
  const unit = currentActor(s)!;
  const def = getMechDefFor(unit);
  const movement = effectiveMovement(def, unit.critSlotsDestroyed);
  const declared = s.moveMode;
  const mode: MoveMode =
    declared === "shutdown" ||
    declared === "startup" ||
    declared === "eject" ||
    declared === "standup" ||
    declared === "drop" ||
    declared === "proneTurn" ||
    declared === null
      ? "standStill"
      : declared;
  return effectiveMoveBudget(mode, movement, unit.heat);
}

/** Resolve a `place` facing argument: an absolute facing word. */
export function resolveFacing(locale: LocaleId, arg: string): Facing {
  const facing = FACINGS.find((f) => f === arg.toLowerCase());
  if (!facing) throw new Error(i18n(locale, "err.faceArg", { facings: FACINGS.join("/") }));
  return facing;
}

/**
 * Buffer the full path to a reachable landing, replacing any previously queued
 * steps. `landing` must come from the current `moveCandidate`; its `path`
 * fragment sequence is replayed from the unit's start, so every enter is
 * necessarily straight ahead/back vs the moving facing and within the mode
 * budget (the candidate was validated by `reachableLandings` at `mode` time).
 * Jump turns are free (engine rejects turn steps), so `R`/`L` fragments only
 * advance the cursor facing and the landing facing travels via `moveFinalFacing`.
 * The buffered landing doubles as the preview source: `status`/`candidate`
 * render `placedLanding.path` directly, no replay.
 */
export function placeLanding(s: Session, landing: RevealedLanding): void {
  const unit = requireActor(s, "movement");
  if (s.moveMode === "shutdown" || s.moveMode === "startup" || s.moveMode === "eject") {
    throw new Error(i18n(s.locale, "err.noMoveInShutdownMode"));
  }
  if (!s.moveMode) throw new Error(i18n(s.locale, "err.declareModeFirst", { id: unit.id }));
  if (s.moveMode === "standStill") throw new Error(i18n(s.locale, "err.standStillNoEnter"));
  const jumping = s.moveMode === "jump";
  const steps: MoveStep[] = [];
  let hex: HexCoord = { ...unit.position };
  let facing: Facing = unit.facing;
  for (const step of landing.path) {
    const frag = step.fragment;
    if (frag === "R" || frag === "L") {
      const delta = frag === "R" ? 1 : -1;
      facing = rotateFacing(facing, delta);
      if (!jumping) steps.push({ kind: "turn", facings: delta });
      continue;
    }
    const isBackward = frag === "B";
    const to = neighbor(hex, isBackward ? oppositeFacing(facing) : facing);
    steps.push({ kind: "enter", to });
    hex = to;
  }
  s.moveSteps = steps;
  s.moveFinalFacing = jumping ? landing.facing : null;
  s.placedLanding = landing;
  s.placedTurn = null;
}

export function queueProneTurn(s: Session, dir: string): void {
  const unit = requireActor(s, "movement");
  if (!unit.prone) throw new Error(i18n(s.locale, "err.turnRequiresProne", { id: unit.id }));
  const d = dir.toLowerCase();
  if (d !== "left" && d !== "right") throw new Error(i18n(s.locale, "err.turnDir"));
  s.moveMode = "proneTurn";
  const facings = d === "left" ? -1 : 1;
  s.moveSteps = [{ kind: "turn", facings }];
  s.moveFinalFacing = null;
  s.placedLanding = null;
  s.placedTurn = facings;
}

export function cancelMove(s: Session): void {
  requireActor(s, "movement");
  s.moveMode = null;
  clearMoveQueue(s);
}

export interface CommitResult {
  state: BattleState;
  newEvents: GameEvent[];
}

/**
 * Apply a commit atomically: on any thrown error the held `s.battle` is rolled
 * back to a snapshot taken before the commit, so a failed validation can never
 * leave live game state partially mutated.
 */
function commitAtomic(s: Session, fn: () => void): void {
  const battle = s.battle;
  if (!battle) return;
  const snapshot = structuredClone(battle);
  try {
    fn();
  } catch (e) {
    s.battle = snapshot;
    throw e;
  }
}

export function commitMove(s: Session): CommitResult {
  const unit = requireActor(s, "movement");
  const battle = requireBattle(s);
  const beforeCount = battle.events.length;
  commitAtomic(s, () => {
    if (s.moveMode === "shutdown") {
      voluntaryShutdown(battle, unit.id);
    } else if (s.moveMode === "startup") {
      attemptVoluntaryStartup(battle, unit.id, s.rng);
    } else if (s.moveMode === "eject") {
      ejectPilot(battle, unit.id);
    } else if (s.moveMode === "standup") {
      attemptStandUp(battle, unit.id, s.rng);
    } else if (s.moveMode === "drop") {
      dropProne(battle, unit.id);
    } else if (s.moveMode === "proneTurn") {
      const step = s.moveSteps[0];
      if (step === undefined || step.kind !== "turn") {
        throw new Error(i18n(s.locale, "err.declareModeFirst", { id: unit.id }));
      }
      proneFacingTurn(battle, unit.id, step.facings);
    } else if (isShutdown(unit)) {
      // Shut-down unit committing without a startup attempt: pass.
      passMovement(battle, unit.id);
    } else {
      executeMove(
        battle,
        unit.id,
        s.moveSteps,
        s.moveFinalFacing === null
          ? { rng: s.rng }
          : { finalFacing: s.moveFinalFacing, rng: s.rng },
      );
    }
    s.actorId = null;
    clearBuffers(s);
    drive(s);
  });
  const newEvents = battle.events.slice(beforeCount);
  return { state: battle, newEvents };
}

// -------------------------------------------------------------- attacks ----

export function cancelFire(s: Session): void {
  requireActor(s, "weaponAttack");
  s.fireDecls = [];
}

export function passFire(s: Session): CommitResult {
  const unit = requireActor(s, "weaponAttack");
  const battle = requireBattle(s);
  const beforeCount = battle.events.length;
  commitAtomic(s, () => {
    unit.passedAttacks = true;
    s.actorId = null;
    clearBuffers(s);
    drive(s);
  });
  return { state: battle, newEvents: battle.events.slice(beforeCount) };
}

/**
 * Read-only mirror of `declareAttacks` gates (no ammo consumed, no state
 * mutated): rejects illegal weapons at queue time so `commitFire` cannot
 * fail on a weapon the suggestion showed as blocked. `declareAttacks`
 * re-validates atomically at commit.
 */
function validateQueuedAttacks(
  battle: BattleState,
  unit: UnitState,
  decls: readonly AttackDecl[],
): void {
  if (unit.destroyed || unit.removed) throw new Error(`${unit.id} is destroyed`);
  if (isShutdown(unit)) throw new Error(`${unit.id} is shut down and cannot fire`);
  if (unit.unconscious) throw new Error(`${unit.id} is unconscious and cannot fire`);
  if (unit.declaredAttacks.length > 0)
    throw new Error(`${unit.id} already declared attacks this turn`);
  const def = getMechDefFor(unit);
  const sensorsOut = countDestroyedStructure(def, unit.critSlotsDestroyed, SENSORS);
  let targetId: string | null = null;
  const seen = new Set<number>();
  for (const decl of decls) {
    const mount = def.weapons[decl.weaponIndex];
    if (!mount) throw new Error(`weaponIndex ${decl.weaponIndex} out of range for ${unit.id}`);
    const weapon = getWeaponDefFor(mount);
    if (seen.has(decl.weaponIndex)) {
      throw new Error(`${mount.weapon} on ${unit.id} may only be declared once per turn`);
    }
    seen.add(decl.weaponIndex);
    if (unit.jammedWeapons.includes(decl.weaponIndex)) {
      throw new Error(`${mount.weapon} on ${unit.id} is jammed`);
    }
    if (unit.destroyedWeapons.includes(decl.weaponIndex)) {
      throw new Error(`${mount.weapon} on ${unit.id} is destroyed by a critical hit`);
    }
    if (!canFireFromLocation(unit.phaseStartDamage, mount.location)) {
      throw new Error(
        `${mount.weapon} location (${mount.location}) is destroyed or its support torso is gone`,
      );
    }
    if (unit.prone && (mount.location === "rightLeg" || mount.location === "leftLeg")) {
      throw new Error(`${mount.weapon} on ${unit.id} cannot fire while prone (leg-mounted)`);
    }
    const rapidFire = decl.rapidFire ?? false;
    if (rapidFire && weapon.rapidFireShots === undefined) {
      throw new Error(`${mount.weapon} is not rapid-fire`);
    }
    const shots = rapidFire ? (weapon.rapidFireShots ?? 1) : 1;
    if (targetId === null) targetId = decl.targetId;
    else if (targetId !== decl.targetId) {
      throw new Error("A unit may only declare attacks against one target per turn");
    }
    const target = battle.units[decl.targetId];
    if (!target) throw new Error(`Unknown unit id: ${decl.targetId}`);
    if (target.removed) throw new Error(`Target ${target.id} is removed from play`);
    if (target.team === unit.team) throw new Error("Target must belong to another team");
    const dist = hexDistance(unit.position, target.position);
    const b = bearingExact(unit.position, target.position);
    if (b === null) throw new Error("Attacker and target share a hex");
    const fireArc = classifyArcWithBoundary(unit.facing, b);
    const rearFacing = mount.rearFacing === true;
    const inArc =
      weaponCanFireIntoArc(mount.location, rearFacing, fireArc.arc) ||
      (fireArc.altArc !== null && weaponCanFireIntoArc(mount.location, rearFacing, fireArc.altArc));
    if (!inArc) {
      throw new Error(
        `${mount.weapon} on ${unit.id} cannot fire into the ${fireArc.arc} arc (target outside its firing arc)`,
      );
    }
    const woodsPoints = losWoodsPointsBetween(battle, unit.position, target.position);
    if (!losClear(battle, unit.position, target.position, battle.wrecks)) {
      throw new Error("Line of sight is blocked");
    }
    if (dist > weapon.long) {
      throw new Error(`${mount.weapon}: target at range ${dist} exceeds long range ${weapon.long}`);
    }
    const breakdown = computeToHit({
      gunnery: unit.gunnery,
      attackerMovement: unit.moveMode ?? "standStill",
      attackerProne: unit.prone,
      sensorMod: sensorsOut,
      targetHexesMoved: target.movesThisTurn.length,
      targetJumped: target.jumpedThisTurn,
      targetImmobile: isImmobile(target),
      targetProne: target.prone,
      targetTerrain: cellAt(battle, target.position).terrain,
      partialCoverMod: partialCoverMod(battle, unit, target),
      interveningWoods: woodsPoints,
      distance: dist,
      weapon,
      attackerLevel: cellAt(battle, unit.position).level,
      targetLevel: cellAt(battle, target.position).level,
      heatMod: toHitHeatModifier(unit.heat),
    });
    if (breakdown.automatic === "miss") {
      throw new Error(
        `${mount.weapon}: modified TN ${breakdown.total} auto-misses; abort the declaration instead`,
      );
    }
    const needed = weapon.missiles !== undefined ? 1 : shots;
    if (binsForWeapon(def, decl.weaponIndex).length > 0) {
      const left = ammoWeaponTotals(def, unit.ammoBins)[decl.weaponIndex] ?? 0;
      if (left < needed) {
        throw new Error(`${mount.weapon}: needs ${needed} shot(s) but only ${left} remain`);
      }
    } else if (binsForWeaponName(def, weapon.name).length > 0) {
      if (pooledShotsLeft(def, unit.ammoBins, weapon.name) < needed) {
        throw new Error(`${mount.weapon}: needs ${needed} shot(s) but pool is empty`);
      }
    }
  }
  if (unit.prone) {
    const hasLeft = decls.some((d) => def.weapons[d.weaponIndex]?.location === "leftArm");
    const hasRight = decls.some((d) => def.weapons[d.weaponIndex]?.location === "rightArm");
    if (hasLeft && hasRight) {
      throw new Error(`${unit.id} cannot fire while prone (volley uses both arms; prop one)`);
    }
  }
}

export function queueFire(s: Session, decl: AttackDecl): void {
  const unit = requireActor(s, "weaponAttack");
  const battle = requireBattle(s);
  if (decl.targetId === unit.id) throw new Error(i18n(s.locale, "err.selfTarget"));
  const target = battle.units[decl.targetId];
  if (!target) throw new Error(i18n(s.locale, "err.unknownUnitId", { id: decl.targetId }));
  if (target.team === unit.team) throw new Error(i18n(s.locale, "err.selfTarget"));
  if (target.removed) throw new Error(i18n(s.locale, "err.targetRemoved", { id: target.id }));
  const pending = s.fireDecls[0]?.targetId;
  if (pending !== undefined && pending !== decl.targetId) {
    throw new Error(i18n(s.locale, "err.oneTarget", { target: pending }));
  }
  if (s.fireDecls.some((d) => d.weaponIndex === decl.weaponIndex)) {
    throw new Error(i18n(s.locale, "err.weaponRepeated", { weapon: decl.weaponIndex }));
  }
  validateQueuedAttacks(battle, unit, [...s.fireDecls, decl]);
  s.fireDecls.push(decl);
}

export function commitFire(s: Session): CommitResult {
  const unit = requireActor(s, "weaponAttack");
  const battle = requireBattle(s);
  if (s.fireDecls.length === 0) throw new Error(i18n(s.locale, "err.noAttacksQueued"));
  validateQueuedAttacks(battle, unit, s.fireDecls);
  const beforeCount = battle.events.length;
  const newEvents: GameEvent[] = [];
  commitAtomic(s, () => {
    declareAttacks(battle, unit.id, s.fireDecls, s.rng);
    const declEvents = battle.events.slice(beforeCount);
    s.actorId = null;
    clearBuffers(s);
    const driveEvents = drive(s);
    newEvents.push(...declEvents, ...driveEvents);
  });
  return { state: battle, newEvents };
}

/**
 * Set the acting unit's ammo-depletion policy. Affects the order its ammo
 * bins are drained by future shots (and which bin explodes on a crit).
 */
export function setAmmoPolicy(s: Session, word: string): void {
  const unit = requireActor(s, "weaponAttack");
  const policy: AmmoPolicy | null = parseAmmoPolicy(word);
  if (policy === null) throw new Error(i18n(s.locale, "err.badAmmoPolicy"));
  unit.ammoPolicy = policy;
}

