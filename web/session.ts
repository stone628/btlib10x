export type AppState = "setup" | "battle" | "over";

export interface SetupUnit extends MechModelHolder {
  readonly id: string;
  readonly model: string;
  readonly team: number;
  readonly gunnery: number;
  /** 1-based coordinates. */
  readonly position: HexCoord;
  readonly facing: Facing;
}

export interface SetupState extends MapNameHolder {
  seed: number;
  mapName: string | null;
  roster: SetupUnit[];
}

export interface Session {
  app: AppState;
  /** Output language (UI preference; preserved across reset/rematch). */
  locale: LocaleId;
  rng: Rng;
  setup: SetupState;
  battle: BattleState | null;
  victory: VictoryResult | null;
  actorId: string | null;
  /** Pending declaration for the acting unit: a movement mode (engine
   *  `MoveMode`) or the voluntary `"shutdown"` / `"startup"` declaration,
   *  committed by the `done` command. */
  moveMode: MoveMode | "shutdown" | "startup" | null;
  moveSteps: MoveStep[];
  fireDecls: AttackDecl[];
  /** Suppress critical hit resolution (mostly for deterministic testing). */
  critsDisabled: boolean;
  moveCandidate: BoardRenderReachableInfo | null;
  /** Actor (turn-qualified) whose fire suggestion was last auto-shown. */
  fireHintShownFor: string | null;
  fireCandidate: FireSuggestion | null;
}

export function newSession(seed: number): Session {
  return {
    app: "setup",
    locale: "en",
    rng: createRng(seed),
    setup: { mapName: null, seed: seed, roster: [] },
    battle: null,
    victory: null,
    actorId: null,
    moveMode: null,
    moveSteps: [],
    fireDecls: [],
    fireHintShownFor: null,
    critsDisabled: false,
    moveCandidate: null,
    fireCandidate: null,
  };
}

function clearBuffers(s: Session): void {
  s.moveMode = null;
  s.moveSteps = [];
  s.fireDecls = [];
}

/**
 * Advance the battle through transient phases until an actor must act or the
 * game ends. Returns the GameEvents generated by the phase transitions
 * (initiative rolls, the end-of-phase attack sweep, turn/phase markers).
 */
function drive(s: Session): GameEvent[] {
  const battle = s.battle;
  if (!battle) return [];
  const before = battle.events.length;
  for (let i = 0; i < 200; i++) {
    const v = checkVictory(battle);
    if (v.winnerTeam !== null || v.draw) {
      s.battle = battle;
      s.app = "over";
      s.victory = v;
      s.actorId = null;
      clearBuffers(s);
      return battle.events.slice(before);
    }
    if (battle.phase === "initiative") {
      rollInitiativePhase(battle, s.rng);
      continue;
    }
    if (battle.phase === "end") {
      advancePhase(battle, s.rng);
      continue;
    }
    const id = nextActor(battle);
    if (id !== null) {
      s.battle = battle;
      s.app = "battle";
      if (s.actorId !== id) {
        s.actorId = id;
        clearBuffers(s);
      }
      return battle.events.slice(before);
    }
    if (battle.phase === "weaponAttack") {
      resolveAllAttacks(battle, s.rng);
    }
    advancePhase(battle, s.rng);
  }
  throw new Error(i18n(s.locale, "err.phaseDriver"));
}

export function currentActor(s: Session): UnitState | null {
  if (s.app !== "battle" || !s.battle || s.actorId === null) return null;
  return getUnit(s.battle, s.actorId);
}

/** Prompt body without the trailing ">". */
export function promptBody(s: Session): string {
  switch (s.app) {
    case "setup":
      return i18n(s.locale, "prompt.setup");
    case "over": {
      const winner = s.victory?.draw
        ? i18n(s.locale, "prompt.draw")
        : i18n(s.locale, "prompt.winnerTeam", { team: s.victory?.winnerTeam ?? "?" });
      return i18n(s.locale, "prompt.over", {
        winner,
        turn: s.battle?.turn ?? "?",
      });
    }
    case "battle": {
      const st = s.battle!;
      const phase =
        st.phase === "movement"
          ? i18n(s.locale, "prompt.subMove")
          : i18n(s.locale, "prompt.subAttack");
      const actor = currentActor(s);
      return i18n(s.locale, "prompt.turn", {
        turn: st.turn,
        phase,
        team: actor?.team ?? "?",
        mech: actor?.id ?? "?",
      });
    }
  }
}

// ---------------------------------------------------------------- setup ----

export function setMap(s: Session, m: MapDef): void {
  if (s.setup.mapName !== null) {
    for (const u of s.setup.roster) {
      if (u.position.col > m.width) {
        throw new Error(
          i18n(s.locale, "err.unitOutOfBounds", {
            id: u.id,
            label: "col",
            value: u.position.col,
            max: m.width,
          }),
        );
      }
      if (u.position.row > m.height) {
        throw new Error(
          i18n(s.locale, "err.unitOutOfBounds", {
            id: u.id,
            label: "row",
            value: u.position.row,
            max: m.height,
          }),
        );
      }
    }
  }
  s.setup.mapName = m.name;
}

export function addUnit(
  s: Session,
  id: string,
  model: string,
  team: number,
  gunnery: number,
  position: HexCoord,
  facing: Facing,
): string {
  const m = lookupMech(model);
  if (m === undefined) throw new Error(i18n(s.locale, "err.unknownModel", { model }));
  if (s.setup.roster.some((u) => u.id === id))
    throw new Error(i18n(s.locale, "err.duplicateId", { id }));
  if (!Number.isInteger(team) || team < 0) throw new Error(i18n(s.locale, "err.badTeam"));
  if (!Number.isInteger(gunnery) || gunnery < 0 || gunnery > 7) {
    throw new Error(i18n(s.locale, "err.badGunnery"));
  }
  if (s.setup.roster.some((u) => sameHex(u.position, position))) {
    throw new Error(i18n(s.locale, "err.hexOccupied", { col: position.col, row: position.row }));
  }
  if (s.setup.mapName != null) {
    const map = getMapDefFor(s.setup);
    if (map !== undefined) {
      if (position.col > map.width) {
        throw new Error(
          i18n(s.locale, "err.outOfBounds", { label: "col", value: position.col, max: map.width }),
        );
      }
      if (position.row > map.height) {
        throw new Error(
          i18n(s.locale, "err.outOfBounds", { label: "row", value: position.row, max: map.height }),
        );
      }
    }
  }
  s.setup.roster.push({ id, model: m.model, team, gunnery, position, facing });
  return m.model;
}

export function removeUnit(s: Session, id: string): void {
  if (!s.setup.roster.some((u) => u.id === id))
    throw new Error(i18n(s.locale, "err.noSuchUnit", { id }));
  s.setup.roster = s.setup.roster.filter((u) => u.id !== id);
}

/** Shared createBattle options: setup terrain plus the loaded map's size. */
function battleOptions(s: Session): CreateBattleOptions {
  return {
    critsDisabled: s.critsDisabled,
  };
}

export function startBattle(s: Session): void {
  if (s.app !== "setup") throw new Error(i18n(s.locale, "err.alreadyStarted"));
  if (s.setup.roster.length < 2) throw new Error(i18n(s.locale, "err.needTwoUnits"));
  const teams = new Set(s.setup.roster.map((u) => u.team));
  if (teams.size < 2) throw new Error(i18n(s.locale, "err.needTwoTeams"));
  const inits: UnitInit[] = s.setup.roster.map((u) => ({ ...u }));
  const map = getMapDefFor(s.setup);
  s.battle = createBattle(map, inits, battleOptions(s));
  s.victory = null;
  s.actorId = null;
  s.fireHintShownFor = null;
  clearBuffers(s);
  drive(s);
}

// ------------------------------------------------------------- movement ----

const MOVE_MODES: Readonly<Record<string, MoveMode>> = {
  standstill: "standStill",
  walk: "walk",
  run: "run",
  jump: "jump",
};

const VOLUNTARY_MODES: Readonly<Record<string, "shutdown" | "startup">> = {
  shutdown: "shutdown",
  startup: "startup",
};

export type DeclaredMode = MoveMode | "shutdown" | "startup";

export function parseMoveMode(locale: LocaleId, word: string): DeclaredMode {
  const mode = MOVE_MODES[word.toLowerCase()];
  if (mode) return mode;
  const voluntary = VOLUNTARY_MODES[word.toLowerCase()];
  if (voluntary) return voluntary;
  throw new Error(i18n(locale, "err.badModeWord"));
}

function requireBattle(s: Session): BattleState {
  if (!s.battle) throw new Error(i18n(s.locale, "err.noBattle"));
  return s.battle;
}

function requireActor(s: Session, phase: "movement" | "weaponAttack"): UnitState {
  const unit = currentActor(s);
  if (!unit || !s.battle || s.battle.phase !== phase) {
    throw new Error(i18n(s.locale, "err.wrongPhase", { phase }));
  }
  return unit;
}

export function declareMode(s: Session, word: string): void {
  const unit = requireActor(s, "movement");
  const mode = parseMoveMode(s.locale, word);
  if (mode === "shutdown") {
    if (isShutdown(unit)) throw new Error(i18n(s.locale, "err.mustBeOnlineForShutdown"));
    s.moveMode = "shutdown";
    s.moveSteps = [];
    return;
  }
  if (mode === "startup") {
    if (unit.shutdown === "not") throw new Error(i18n(s.locale, "err.mustBeDownForStartup"));
    if (unit.shutdown === "starting") throw new Error(i18n(s.locale, "err.alreadyStarting"));
    s.moveMode = "startup";
    s.moveSteps = [];
    return;
  }
  declareMove(requireBattle(s), unit.id, mode);
  s.moveMode = mode;
  s.moveSteps = [];
}

interface MoveCursor {
  hex: HexCoord;
  facing: Facing;
  spent: number;
}

function replaySteps(s: Session): MoveCursor {
  const unit = currentActor(s)!;
  const cur: MoveCursor = { hex: { ...unit.position }, facing: unit.facing, spent: 0 };
  for (const step of s.moveSteps) {
    if (step.kind === "turn") {
      cur.facing = rotateFacing(cur.facing, step.facings);
      cur.spent += facingChangeCost(Math.abs(step.facings));
    } else {
      const battle = requireBattle(s);
      const fromLevel = cellAt(battle, cur.hex).level;
      const toLevel = cellAt(battle, step.to).level;
      cur.hex = { ...step.to };
      if (s.moveMode === "jump") {
        cur.spent += 1;
      } else {
        cur.spent += costToEnter(cellAt(battle, step.to).terrain) + costToClimb(fromLevel, toLevel);
      }
    }
  }
  return cur;
}

function budgetFor(s: Session): number {
  const unit = currentActor(s)!;
  const def = getMechDefFor(unit);
  const movement = effectiveMovement(def, unit.critSlotsDestroyed);
  const mode: MoveMode =
    s.moveMode === "shutdown" || s.moveMode === "startup" || s.moveMode === null
      ? "standStill"
      : s.moveMode;
  return effectiveMoveBudget(mode, movement, unit.heat);
}

export interface StepResult {
  readonly position: HexCoord;
  facing: Facing;
  readonly mpSpent: number;
  readonly mpBudget: number;
}

/** Cursor state after replaying all queued movement steps. */
export function stepResult(s: Session): StepResult {
  const cur = replaySteps(s);
  return {
    position: cur.hex,
    facing: cur.facing,
    mpSpent: cur.spent,
    mpBudget: budgetFor(s),
  };
}

export function queueEnter(s: Session, to: HexCoord): void {
  const unit = requireActor(s, "movement");
  if (s.moveMode === "shutdown" || s.moveMode === "startup") {
    throw new Error(i18n(s.locale, "err.noMoveInShutdownMode"));
  }
  if (!s.moveMode) throw new Error(i18n(s.locale, "err.declareModeFirst", { id: unit.id }));
  if (sameHex(unit.position, to)) throw new Error(i18n(s.locale, "err.sameHexMove"));
  const cur = replaySteps(s);
  if (sameHex(cur.hex, to)) throw new Error(i18n(s.locale, "err.alreadyThere"));
  if (s.moveMode === "standStill") throw new Error(i18n(s.locale, "err.standStillNoEnter"));
  const battle = requireBattle(s);
  let cost: number;
  if (s.moveMode === "jump") {
    if (!isAdjacent(cur.hex, to)) throw new Error(i18n(s.locale, "err.jumpNotAdjacent"));
    cost = 1;
  } else {
    const forward = isForwardStep(cur.hex, to, cur.facing);
    const backward = !forward && isBackwardStep(cur.hex, to, cur.facing);
    if (!forward && !backward) {
      throw new Error(i18n(s.locale, "err.groundStraightOnly"));
    }
    const fromLevel = cellAt(battle, cur.hex).level;
    const toLevel = cellAt(battle, to).level;
    if (toLevel - fromLevel > 1) {
      throw new Error(i18n(s.locale, "err.climbTooSteep", { col: to.col, row: to.row }));
    }
    cost = costToEnter(cellAt(battle, to).terrain) + costToClimb(fromLevel, toLevel);
  }
  const spent = cur.spent + cost;
  const budget = budgetFor(s);
  if (spent > budget) {
    throw new Error(i18n(s.locale, "err.mpExceeded", { spent, mode: s.moveMode, budget }));
  }
  s.moveSteps.push({ kind: "enter", to });
}

export function queueTurn(s: Session, facings: number): void {
  const unit = requireActor(s, "movement");
  if (s.moveMode === "shutdown" || s.moveMode === "startup") {
    throw new Error(i18n(s.locale, "err.noMoveInShutdownMode"));
  }
  if (!s.moveMode) throw new Error(i18n(s.locale, "err.declareModeFirst", { id: unit.id }));
  if (s.moveMode === "standStill") throw new Error(i18n(s.locale, "err.standStillNoFace"));
  if (s.moveMode === "jump") throw new Error(i18n(s.locale, "err.jumpFreeFacing"));
  if (!Number.isInteger(facings) || facings === 0 || Math.abs(facings) > 5) {
    throw new Error(i18n(s.locale, "err.badFacings"));
  }
  const cur = replaySteps(s);
  const spent = cur.spent + facingChangeCost(Math.abs(facings));
  const budget = budgetFor(s);
  if (spent > budget) {
    throw new Error(i18n(s.locale, "err.mpExceeded", { spent, mode: s.moveMode, budget }));
  }
  s.moveSteps.push({ kind: "turn", facings });
}

/** Resolve a `face` argument: absolute facing name or signed step count. */
export function faceSteps(locale: LocaleId, current: Facing, arg: string): number {
  if (/^[+-]?\d+$/.test(arg)) {
    const n = Number(arg);
    if (!Number.isInteger(n) || n === 0 || Math.abs(n) > 5) {
      throw new Error(i18n(locale, "err.badFacings"));
    }
    return n;
  }
  const target = FACINGS.find((f) => f === arg.toLowerCase());
  if (!target) throw new Error(i18n(locale, "err.faceArg", { facings: FACINGS.join("/") }));
  const delta0 = FACINGS.indexOf(target) - FACINGS.indexOf(current);
  const delta = delta0 > 3 ? delta0 - 6 : delta0 < -3 ? delta0 + 6 : delta0;
  if (delta === 0) throw new Error(i18n(locale, "err.faceCurrent", { facing: current }));
  return delta;
}

export function cancelMove(s: Session): void {
  requireActor(s, "movement");
  s.moveMode = null;
  s.moveSteps = [];
}

export interface CommitResult {
  state: BattleState;
  newEvents: BattleState["events"];
}

/**
 * Apply a commit atomically: on any thrown error the held `s.battle` is rolled
 * back to a snapshot taken before the commit, so a failed validation can never
 * leave live game state partially mutated.
 */
function commitAtomic(s: Session, fn: () => void): void {
  const battle = s.battle;
  if (!battle) return;
  const snapshot = structuredClone(battle);
  try {
    fn();
  } catch (e) {
    s.battle = snapshot;
    throw e;
  }
}

export function commitMove(s: Session): CommitResult {
  const unit = requireActor(s, "movement");
  const battle = requireBattle(s);
  const beforeCount = battle.events.length;
  commitAtomic(s, () => {
    if (s.moveMode === "shutdown") {
      voluntaryShutdown(battle, unit.id);
    } else if (s.moveMode === "startup") {
      attemptVoluntaryStartup(battle, unit.id, s.rng);
    } else if (isShutdown(unit)) {
      // Shut-down unit committing without a startup attempt: pass.
      passMovement(battle, unit.id);
    } else {
      executeMove(battle, unit.id, s.moveSteps);
    }
    s.actorId = null;
    clearBuffers(s);
    drive(s);
  });
  const newEvents = battle.events.slice(beforeCount);
  return { state: battle, newEvents };
}

export interface MoveStepInfo {
  readonly label: string;
  readonly mpCost: number;
  readonly mpAfter: number;
}

/** Queued movement steps with running MP totals, for `status`. */
export function moveStepsInfo(s: Session): {
  mode: DeclaredMode | null;
  steps: MoveStepInfo[];
  budget: number;
} {
  const unit = currentActor(s);
  if (!unit || !s.battle) throw new Error(i18n(s.locale, "err.needsActor"));
  const battle = s.battle;
  const steps: MoveStepInfo[] = [];
  let _hex: HexCoord = { ...unit.position };
  let facing: Facing = unit.facing;
  let spent = 0;
  s.moveSteps.forEach((step, i) => {
    let label: string;
    let cost: number;
    if (step.kind === "turn") {
      const nextFacing = rotateFacing(facing, step.facings);
      label = i18n(s.locale, "moveStatus.stepTurn", {
        i: i + 1,
        steps: signed(step.facings),
        from: facing,
        to: nextFacing,
      });
      facing = nextFacing;
      cost = facingChangeCost(Math.abs(step.facings));
    } else {
      label = i18n(s.locale, "moveStatus.stepEnter", {
        i: i + 1,
        col: step.to.col,
        row: step.to.row,
      });
      const fromLevel = cellAt(battle, _hex).level;
      const toLevel = cellAt(battle, step.to).level;
      _hex = { ...step.to };
      if (s.moveMode === "jump") {
        cost = 1;
      } else {
        cost = costToEnter(cellAt(battle, step.to).terrain) + costToClimb(fromLevel, toLevel);
      }
    }
    spent += cost;
    steps.push({ label, mpCost: cost, mpAfter: spent });
  });
  return { mode: s.moveMode, steps, budget: budgetFor(s) };
}

function signed(n: number): string {
  return n >= 0 ? `+${n}` : String(n);
}

// -------------------------------------------------------------- attacks ----

export function cancelFire(s: Session): void {
  requireActor(s, "weaponAttack");
  s.fireDecls = [];
}

export function passFire(s: Session): CommitResult {
  const unit = requireActor(s, "weaponAttack");
  const battle = requireBattle(s);
  const beforeCount = battle.events.length;
  commitAtomic(s, () => {
    unit.passedAttacks = true;
    s.actorId = null;
    clearBuffers(s);
    drive(s);
  });
  return { state: battle, newEvents: battle.events.slice(beforeCount) };
}

export function queueFire(s: Session, decl: AttackDecl): void {
  const unit = requireActor(s, "weaponAttack");
  if (decl.targetId === unit.id) throw new Error(i18n(s.locale, "err.selfTarget"));
  const target = requireBattle(s).units[decl.targetId];
  if (!target) throw new Error(i18n(s.locale, "err.unknownUnitId", { id: decl.targetId }));
  if (target.team === unit.team) throw new Error(i18n(s.locale, "err.selfTarget"));
  if (target.removed) throw new Error(i18n(s.locale, "err.targetRemoved", { id: target.id }));
  const pending = s.fireDecls[0]?.targetId;
  if (pending !== undefined && pending !== decl.targetId) {
    throw new Error(i18n(s.locale, "err.oneTarget", { target: pending }));
  }
  if (s.fireDecls.some((d) => d.weaponIndex === decl.weaponIndex)) {
    throw new Error(i18n(s.locale, "err.weaponRepeated", { weapon: decl.weaponIndex }));
  }
  s.fireDecls.push(decl);
}

export function commitFire(s: Session): CommitResult {
  const unit = requireActor(s, "weaponAttack");
  const battle = requireBattle(s);
  const beforeCount = battle.events.length;
  let declEvents: BattleState["events"] = [];
  let driveEvents: BattleState["events"] = [];
  commitAtomic(s, () => {
    declareAttacks(battle, unit.id, s.fireDecls, s.rng);
    declEvents = battle.events.slice(beforeCount);
    s.actorId = null;
    clearBuffers(s);
    driveEvents = drive(s);
  });
  return { state: battle, newEvents: [...declEvents, ...driveEvents] };
}

/**
 * Set the acting unit's ammo-depletion policy. Affects the order its ammo
 * bins are drained by future shots (and which bin explodes on a crit).
 */
export function setAmmoPolicy(s: Session, word: string): void {
  const unit = requireActor(s, "weaponAttack");
  const policy: AmmoPolicy | null = parseAmmoPolicy(word);
  if (policy === null) throw new Error(i18n(s.locale, "err.badAmmoPolicy"));
  unit.ammoPolicy = policy;
}

// ------------------------------------------------------------ lifecycle ----

export function rematch(s: Session): void {
  if (s.app !== "over") throw new Error(i18n(s.locale, "err.rematchOnlyOver"));
  s.rng = createRng(s.setup.seed);
  s.battle = createBattle(
    getMapDefFor(s.setup),
    s.setup.roster.map((u) => ({ ...u })),
    battleOptions(s),
  );
  s.victory = null;
  s.actorId = null;
  s.fireHintShownFor = null;
  clearBuffers(s);
  drive(s);
}

export function resetSession(s: Session): void {
  s.app = "setup";
  s.setup = { mapName: null, roster: [], seed: s.setup.seed };
  s.battle = null;
  s.victory = null;
  s.actorId = null;
  s.fireHintShownFor = null;
  clearBuffers(s);
}

export function setSeed(s: Session, n: number): void {
  if (!Number.isInteger(n)) throw new Error(i18n(s.locale, "err.seedInteger"));
  s.setup.seed = n >>> 0;
  s.rng = createRng(s.setup.seed);
}
